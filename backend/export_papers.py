"""Export each room's reading material for the front end (frontend/papers.js).

Click the newspaper, the teletype, the official's files or the historian's
books in a painted room and you get that role's view of the day, built from
the story packs, so it follows the same rules as the host:

  citizen     newspaper   public facts dated that day
  journalist  wire copy   facts a reporter could have that day (public first)
  official    files       facts only insiders had that day, then the rest
  historian   books       hindsight: facts only the historian may know

Run after changing a pack:  python export_papers.py   (from backend/)
"""
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).parent
STATIONS = {  # the dial's stations (frontend/stations.js) and their packs
    "1962-10-16": "cmc-1962", "1962-10-22": "cmc-1962", "1962-10-24": "cmc-1962",
    "1962-10-27": "cmc-1962", "1962-10-28": "cmc-1962",
    "1969-07-20": "apollo-1969", "1989-11-09": "berlin-1989",
}
PER_PAPER = 5


def load(pack):
    facts = {}
    for f in sorted((ROOT / "packs" / pack).glob("*.json")):
        for x in json.loads(f.read_text(encoding="utf-8")).get("facts", []):
            facts.setdefault(x["id"], x)
    return list(facts.values())


def item(x):
    src = x["source"]
    return {"date": x["date"], "text": x["text"].strip(), "quote": x.get("quote") or None,
            "source": src["title"], "url": src.get("url") or None}


def pick(facts, day, role):
    roles = lambda x: set(x["roles"])
    if role == "historian":
        # Hindsight first (historian-only facts), newest last so the story reads in order.
        only = sorted((x for x in facts if roles(x) == {"historian"}), key=lambda x: x["date"])
        return only[:PER_PAPER]
    seen = [x for x in facts if role in roles(x) and x["date"] <= day]
    today = [x for x in seen if x["date"] == day]
    if role == "official":
        # The insider view: what the public didn't have, then the rest of the day.
        today.sort(key=lambda x: "citizen" in roles(x))
    elif role == "journalist":
        today.sort(key=lambda x: "citizen" not in roles(x))
    if len(today) < 3:  # a quiet day: fill in with the most recent earlier facts
        earlier = sorted((x for x in seen if x["date"] < day), key=lambda x: x["date"], reverse=True)
        today += earlier[: 3 - len(today)]
    return today[:PER_PAPER]


def main():
    out = defaultdict(dict)
    for day, pack in STATIONS.items():
        facts = load(pack)
        for role in ("citizen", "journalist", "official", "historian"):
            out[day][role] = [item(x) for x in pick(facts, day, role)]
    js = ("// Generated by backend/export_papers.py from the story packs. Don't edit by hand.\n"
          "// PAPERS[stationDate][role] = [{ date, text, quote, source, url }]\n"
          f"export const PAPERS = {json.dumps(out, ensure_ascii=False, indent=1)};\n")
    path = ROOT.parent / "frontend" / "papers.js"
    path.write_text(js, encoding="utf-8")
    n = sum(len(v) for d in out.values() for v in d.values())
    print(f"wrote {path} ({n} items)")


if __name__ == "__main__":
    main()
